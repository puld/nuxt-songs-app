import { joinUrl } from './share'

/**
 * Откуда берётся база песен.
 *
 * Два правила, каждое написано кровью боевого бага:
 *
 *  1. **Путь абсолютный, от `app.baseURL`.** Относительный `assets/songs.json`
 *     разрешается от текущего адреса, а он не всегда корневой: GitHub Pages
 *     редиректит `/nuxt-songs-app/about` на `/about/` с завершающим слэшем, и
 *     запрос уходил в `/nuxt-songs-app/about/assets/songs.json` → 404. При
 *     навигации внутри SPA слэша нет, поэтому путь случайно разрешался верно —
 *     ломалось только открытие по прямой ссылке, закладке или ярлыку PWA.
 *
 *  2. **Кэш ревалидируется (`cache: 'no-cache'`).** Файл отдаётся с
 *     `cache-control: max-age=600`, и без этого браузер десять минут отвечает
 *     из своего кэша старой копией: ответ 200, JSON валиден, запись в базу
 *     проходит — кнопка «Обновить базу» рапортует успех, обновив базу тем же
 *     старым файлом. `no-cache` не отключает кэш, а заставляет спросить сервер:
 *     не изменилось — 304 и та же копия почти без трафика, изменилось — свежий
 *     файл. По той же причине опция нужна и HEAD-проверке ETag: прочитанный из
 *     кэша ETag всегда равен сохранённому, и обновление не находится никогда.
 */

/** Путь к базе песен относительно корня приложения. */
export const SONGS_JSON_PATH = 'assets/songs.json'

/** Опции запроса базы песен: ревалидация вместо ответа из кэша. */
export const SONGS_FETCH_INIT = { cache: 'no-cache' }

/**
 * Адрес базы песен от корня сайта.
 *
 * @param {string} baseURL — `app.baseURL` приложения (`/` или `/nuxt-songs-app/`)
 * @returns {string} абсолютный путь к `songs.json`
 */
export function songsJsonUrl(baseURL) {
    return joinUrl(baseURL || '/', SONGS_JSON_PATH)
}
