/**
 * Версия базы песен на стороне приложения.
 *
 * В корне `songs.json` лежит целое `version` — ручной счётчик из
 * `songs-data/version.txt`, который двигают при значимых изменениях данных.
 * Приложение запоминает его при загрузке базы, чтобы ссылка на подборку могла
 * сказать получателю «сначала обнови базу»: сама ссылка несёт номера песен и
 * индексы вариантов, а не тексты.
 */

/** Версия базы, у которой счётчика ещё нет. */
export const DEFAULT_SONGS_VERSION = 0

/**
 * Приводит значение к версии базы.
 *
 * Значение приходит либо из `songs.json` (файл могли отдать из кэша PWA от
 * старой сборки — поля просто нет), либо из localStorage, где может оказаться
 * что угодно. Непригодное значение — это «версия неизвестна», то есть самая
 * старая: так сравнение ошибётся в безопасную сторону — предложит обновить
 * базу, а не примет подборку, для которой в базе нет песен.
 *
 * @param {unknown} value
 * @returns {number} целое неотрицательное
 */
export function normalizeSongsVersion(value) {
    const num = typeof value === 'string' ? Number(value) : value

    return Number.isSafeInteger(num) && num >= 0 ? num : DEFAULT_SONGS_VERSION
}
