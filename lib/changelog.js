/**
 * Сколько версий показывать до нажатия «Показать все».
 *
 * Список длинный и растёт, а интересны обычно последние: разворот прячет
 * историю, но не выкидывает её.
 */
export const CHANGELOG_PREVIEW = 3

/**
 * Дата версии в виде `ДД.ММ.ГГГГ`.
 *
 * Форматируем вручную, а не через `toLocaleDateString`: строка одинаково
 * выглядит на любом устройстве — её пересылают скриншотом вместе с версией.
 *
 * @param {string} iso — дата в формате `YYYY-MM-DD`
 * @returns {string} пустая строка, если формат не тот
 */
export const formatChangelogDate = (iso) => {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ''))

    if (!match) return ''

    const [, year, month, day] = match

    return `${day}.${month}.${year}`
}

/**
 * Записи для показа: либо все, либо первые `limit`.
 *
 * @param {ChangelogEntry[]} entries
 * @param {boolean} expanded
 * @param {number} limit
 * @returns {ChangelogEntry[]}
 */
export const visibleChangelog = (entries, expanded, limit = CHANGELOG_PREVIEW) => {
    const list = Array.isArray(entries) ? entries : []

    return expanded ? list : list.slice(0, Math.max(0, limit))
}

/**
 * Есть ли что разворачивать — кнопка «Показать все» без этого бессмысленна.
 *
 * @param {ChangelogEntry[]} entries
 * @param {number} limit
 * @returns {boolean}
 */
export const hasMoreChangelog = (entries, limit = CHANGELOG_PREVIEW) => (
    (Array.isArray(entries) ? entries.length : 0) > Math.max(0, limit)
)
