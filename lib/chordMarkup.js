/**
 * Разметка аккордов в тексте песни: `{Am}` над строкой, `{_G}` в строке.
 *
 * Надпись над строкой (`chord-label`) вставляется прямо перед своим слогом и
 * выводится из потока стилями (`position: absolute` без координат берёт то место,
 * где элемент стоял бы в строке). Поэтому текст песни верстается ровно так же,
 * как без аккордов: ни слово, ни пробел не раздвигаются, переносы не смещаются.
 *
 * Обёртки вокруг слова нет сознательно. Разметка повторов расставляется **до**
 * аккордов, её `<span>` не обязан укладываться в границы слова — любая обёртка
 * перекрещивалась бы с ним (в сборнике аккорды и повторы соседствуют в
 * подавляющем большинстве строф). Надпись без обёртки вложенности не создаёт и
 * пересечься ни с чем не может.
 *
 * Плата за вывод из потока — наложение надписей там, где гармония меняется на
 * каждом слоге. Раздвигает их `lib/chordLayout.js` по измерениям браузера.
 *
 * Номер прохода повтора (`{2:Dm}`) — см. `passesOf` ниже.
 */

/**
 * Пометка прохода повтора: `{2:Dm}` — аккорд звучит только во втором проходе,
 * `{1,3:F}` — в первом и третьем, `{Dm}` — в каждом.
 *
 * Зачем пометка внутри скобок, а не вторым экземпляром текста: у Эппа второй
 * проход репризы выписан вольтой со своей гармонией — аккорды там стоят на
 * других слогах и в другом количестве, соответствия «аккорд к аккорду» нет.
 * Дублировать ради этого текст значило бы держать одну строфу в двух местах и
 * править опечатку дважды; пометка же оставляет текст единственным, а каждому
 * проходу даёт независимую раскладку аккордов.
 *
 * Номер относится к **ближайшему охватывающему** повтору `/…/Nр.`; разворачивает
 * такой повтор `lib/repeats.js` при отрисовке.
 */
const PASS = '(?:(\\d+(?:,\\d+)*):)?'

/** Аккорд в строке: `{_G}` — над словом не поднимается. */
const INLINE_RE = new RegExp(`\\{${PASS}_([^}]*)\\}`, 'g')

/** Аккорд над строкой. */
const ABOVE_RE = new RegExp(`\\{${PASS}([^}]*)\\}`, 'g')

/** Любой аккорд — когда показывать их не нужно. */
const ANY_RE = /\{[^}]*\}/g

/** Аккорд с пометкой прохода — целиком, вместе с ней. */
const PASS_RE = /\{(\d+(?:,\d+)*):([^}]*)\}/g

/**
 * Расставляет разметку аккордов в тексте, где повторы уже обработаны.
 *
 * Пометка прохода к этому моменту уже снята раскрытием повтора; уцелевшую
 * (аккорд помечен, а повтора вокруг нет — такие данные бракует линтер) надпись
 * не показываем вместе с номером: «2:Dm» над слогом читалось бы как аккорд.
 *
 * @param {string} html — текст с `{…}`, HTML в остальном уже экранирован
 * @param {boolean} show — показывать ли аккорды
 * @returns {string} HTML
 */
export function renderChords(html, show) {
  if (!html) return ''
  if (!show) return html.replace(ANY_RE, '')

  return html
    .replace(INLINE_RE, "<span class='chord'>$2</span>")
    .replace(ABOVE_RE, "<i class='chord-label' aria-hidden='true'>$2</i>")
}

/** Есть ли в тексте аккорды — строке с ними нужен больший межстрочный интервал. */
export function hasChords(text) {
  return Boolean(text) && text.includes('{')
}

/** Есть ли в тексте аккорд, помеченный проходом, — только такой повтор разворачивается. */
export function hasPassChords(text) {
  if (!text) return false
  PASS_RE.lastIndex = 0
  return PASS_RE.test(String(text))
}

/**
 * Номера проходов аккорда: `'2'` → `[2]`, `'1,3'` → `[1, 3]`, пусто → `null`
 * («звучит в каждом проходе»).
 */
export function passesOf(mark) {
  if (!mark) return null
  const list = String(mark)
    .split(',')
    .map((part) => Number(part))
    .filter((n) => Number.isInteger(n) && n > 0)
  return list.length ? list : null
}

/**
 * Оставляет в тексте аккорды одного прохода повтора и снимает пометки.
 *
 * Аккорд без пометки достаётся каждому проходу: гармония чаще всего совпадает,
 * и требовать пометку у всех означало бы утроить разметку ради нескольких
 * расхождений.
 *
 * @param {string} text — сырой текст фрагмента (HTML ещё не экранирован)
 * @param {number} pass — номер прохода, начиная с 1
 * @returns {string}
 */
export function chordsForPass(text, pass) {
  if (!text) return ''
  return String(text).replace(PASS_RE, (whole, mark, chord) => {
    const passes = passesOf(mark)
    if (passes && !passes.includes(pass)) return ''
    return `{${chord}}`
  })
}
