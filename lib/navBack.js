/**
 * Куда вести кнопку «Назад» в навбаре.
 *
 * Приложение всё чаще открывают не с главной, а сразу на внутреннем экране:
 * присланная ссылка на песню, ссылка на подборку, закладка, ярлык PWA. В такой
 * сессии предыдущей записи истории нет вовсе, и `router.back()` уводит из
 * приложения — в браузере это стартовая страница, в установленном PWA пустой
 * экран. Именно так баг и пришёл от пользователя со страницы приёма ссылки.
 *
 * Отличить эти два случая позволяет `history.state.back`: vue-router кладёт туда
 * адрес предыдущей записи своей истории и оставляет пустым, когда запись первая.
 * Считать `history.length` нельзя — она общая на вкладку и растёт от чужих
 * страниц, открытых до нашей.
 */

/** Куда уходить, если возвращаться некуда. */
export const HOME_ROUTE = '/'

/**
 * Адрес запасного перехода или `null`, если можно вернуться назад по истории.
 *
 * @param {{back?: string|null}|null|undefined} state — `window.history.state`
 * @param {string} [home] — куда уходить без истории
 * @returns {string|null} `null` значит «звать `router.back()`»
 */
export const backTarget = (state, home = HOME_ROUTE) => (
    state && state.back ? null : home
)
