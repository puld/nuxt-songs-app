# -*- coding: utf-8 -*-
"""Буквенные обозначения гармонии: «B♭m», «D7/F♯», «Es» → аккорд ABC над нотой.

Их долго не было видно по той же причине, что и динамику: набраны они не
текстовым шрифтом, а своим — OpusChords / OpusChordsStd, где бемоль, диез, знак
минора и «sus» занимают собственные коды («B¨‹» — это B, бемоль, минор), а
«maj» набран лигатурой из трёх глифов.

В ABC аккорд — строка в кавычках перед нотой (`"Bbm"d`), и abcjs печатает её
над станом сам. Вешается он на верхний голос: в PDF он и стоит над верхним
станом, а «аккорд на систему» в ABC выразить нечем.

Каталог Эппа набран **немецкой** нотацией, причём слоговой: бемоль и диез там
не знак, а часть названия ступени — «Es» (Eb), «As» (Ab), «Fis» (F#), «Des»
(Db). Английский разбор такие обозначения отвергал целиком: из 44 726 знаков
каталога опознавалась едва половина.
"""
import re, meta

# коды аккордового шрифта: знаки альтерации и минора набраны глифами, а не
# буквами, поэтому в текст страницы приезжают отдельными символами
SIGN = {"¨": "b", "©": "#", "‹": "m", "“": "sus", "&": "+",
        # 974 набран шрифтом без объявленной кодировки, и `glyphtext` опознаёт
        # его знаки по контурам: косая черта басовой ноты похожа на «I», а
        # диез в аккордовом шрифте не совпал ни с одним нотным глифом
        "I": "/", "\r": "#"}

# составные обозначения набраны лигатурой из нескольких глифов, поэтому
# разбираются до посимвольной подстановки. Порядок важен: «Ø7» — это целиком
# полууменьшённый септаккорд, и распасться на «Ø» и «7» он не должен
LIGATURES = [("Œ„Š", "maj"), ("„ˆˆ", "add"), ("Ø7", "m7b5"), ("Ø", "m7b5"),
             ("º", "dim")]

# немецкие названия ступеней. Бемоль — слог «es» («Des»), но у A и E он
# сливается с буквой («As», «Es»); диез — слог «is» («Fis»). «H» — это си, а
# «B» — си-бемоль, и в этом английская нотация с немецкой расходится молча:
# спутать их значит сыграть полтона мимо, не получив ни одной ошибки разбора
GERMAN = {"Cis": "C#", "Dis": "D#", "Eis": "E#", "Fis": "F#", "Gis": "G#",
          "Ais": "A#", "His": "B#",
          "Ces": "Cb", "Des": "Db", "Es": "Eb", "Fes": "Fb", "Ges": "Gb",
          "As": "Ab", "B": "Bb", "H": "B"}

ROOT = re.compile(r"^([A-H])(is|es|s)?")
SUFFIX = re.compile(r"^(m|maj|min|dim|aug|sus|add|M|\+)?\d*"
                    r"(b5|#5|b9|#9|#11|b13)?(sus\d?|add\d+)?(\([^)]*\))?$")
# Си-бемоль, набранный **глифом**: «B» и знак бемоля, до `unglyph`. Единственный
# признак, по которому голое «B» листа читается однозначно, — см. `b_is_flat`
BFLAT_GLYPH = re.compile(r"B¨")

# немецкий набор, опознаваемый однозначно: «H» английской записи неизвестно
# вовсе, слоговых ступеней в ней не бывает. Лист с таким признаком читает «B»
# как си-бемоль — так у немцев и заведено
GERMAN_GLYPH = re.compile(r"\b(?:[A-H](?:is|es)|[AE]s(?!us)|H)")

# ступени в полутонах: нужны, чтобы спросить у самого обозначения, сходится ли
# бас с аккордом — см. `_bass_vote`
PITCH = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}

# из каких ступеней аккорд состоит: бас берут из них, а не откуда попало.
# Септима включена, секста тоже — «Am6/F#» в сборнике встречается
TRIAD_MAJOR = (0, 4, 7, 9, 10, 11)
TRIAD_MINOR = (0, 3, 7, 9, 10, 11)

# из чего может состоять готовое обозначение. Проверка нужна ради скобок: SUFFIX
# пускает внутрь них что угодно, и необработанный глиф уезжал в ABC под видом
# аккорда — «D7(„ˆˆ9)» печаталось над станом как есть
# ступени — только A–G: «H» тут не пропуск, а сторож. В английском наборе такой
# ступени нет, и дойти сюда она может лишь при неверно определённом наборе
ALLOWED = set("ABCDEFG") | set("abcdefgijmnsu") | set("M0123456789#+()/")


def unglyph(raw):
    """Текст обозначения из PDF в обычных символах."""
    s = raw
    for lig, name in LIGATURES: s = s.replace(lig, name)
    return "".join(SIGN.get(c, c) for c in s).strip()


def _pitch(name):
    """Ступень ABC («Bb», «F#») в полутонах. None — не ступень."""
    p = PITCH.get(name[:1])
    if p is None: return None
    for c in name[1:]:
        if c == "b": p -= 1
        elif c == "#": p += 1
        else: return None
    return p % 12


def _fits(s, b_flat):
    """Сходится ли обозначение с басом при этой гипотезе про голое «B».

    Бас обязан входить в свой аккорд: «Gm/Bb» — терция в басу, а «Gm/B» терции
    минорному аккорду не даёт вовсе. Ровно это и отличает си от си-бемоля там,
    где текст листа молчит: одна из двух гипотез оставляет обозначение
    бессмысленным.
    """
    parts = s.split("/")
    if len(parts) != 2: return None
    head, bass = _root(parts[0], b_flat), _root(parts[1], b_flat)
    if head is None or bass is None or head[0] is None or bass[0] is None: return None
    if bass[1]: return None
    r, b = _pitch(head[0]), _pitch(bass[0])
    if r is None or b is None: return None
    triad = TRIAD_MINOR if head[1][:1] == "m" and head[1][:3] != "maj" else TRIAD_MAJOR
    return (b - r) % 12 in triad


def _bass_vote(texts):
    """Что говорят про голое «B» басы этого листа: True — си-бемоль, None — молчат.

    Спрашиваются только обозначения, где «B» вообще участвует, и только те, у
    которых гипотезы расходятся: «C/B» согласуется одинаково плохо с обеими
    (ни си, ни си-бемоль в до-мажорное трезвучие не входят) и голоса не даёт.
    """
    flat = sharp = 0
    for t in texts:
        s = unglyph(t)
        if "/" not in s or "B" not in s: continue
        if GERMAN_GLYPH.search(s) or BFLAT_GLYPH.search(t): continue
        a, b = _fits(s, True), _fits(s, False)
        if a and not b: flat += 1
        elif b and not a: sharp += 1
    if flat == sharp: return None
    return flat > sharp


def b_is_flat(texts, nsig=None):
    """Голое «B» на этом листе — си-бемоль? Признак берётся по всему файлу.

    Это единственное место, где немецкая запись расходится с английской молча:
    «B» у немцев си-бемоль, у англичан си, и спутать их значит сыграть полтона
    мимо, не получив ни одной ошибки разбора. Остальные расхождения однозначны
    сами по себе — «H» английский набор не знает вовсе, а слоговых ступеней
    («Es», «Fis») в нём не бывает, так что и решать по ним нечего.

    Доводы спрашиваются по убыванию надёжности, и первый же сработавший решает:

    1. **Си-бемоль напечатан знаком** («B♭») — значит голое «B» гравёр оставил
       за си. Так на `pdf/1473.pdf`, где рядом стоят «Bbm» и «Bm».
    2. **На листе есть «H» или слоговая ступень** — набор немецкий, «B» это
       си-бемоль. Признак прямой: в английской записи ни того, ни другого нет.
    3. **Басы самого листа** (`_bass_vote`): «Gm/B» осмысленно только как
       Gm/Bb, «G/B» — только как соль с си в басу. Довод сильнее ключа, потому
       что относится к конкретным обозначениям, а не к листу вообще: на 1104
       ключ диезный (G-dur), а «Gm/B» там всё равно си-бемоль.
    4. **Ключевые знаки** (`nsig`): бемольный ключ — си-бемоль, диезный — си.
       Последний довод для листов, где не сказано ничего: их 335 из 1419 с
       голым «B», и 291 из них бемольные.

    Прежде вопрос решался одним признаком «немецкий ли набор», и лист без
    слоговых ступеней объявлялся английским: сборнику это стоило 583 обозначения
    в 50 песнях, ушедших в выгрузку на полтона выше. Рамка была неверна и по
    сути — набор смешивается **внутри** листа: на 1536 соседствуют «Es» и
    «Cm/Eb», а на 1950t — «Eb/B», где бемоль набран знаком, а си-бемоль слогом.

    Замер по каталогу (3184 листа с гармонией): голое «B» — на 1419, си-бемоль
    знаком — на трёх, и вместе они встретились единственный раз — на том самом
    английском `pdf/1473.pdf`.
    """
    if any(BFLAT_GLYPH.search(t) for t in texts): return False
    if any(GERMAN_GLYPH.search(unglyph(t)) for t in texts): return True
    vote = _bass_vote(texts)
    if vote is not None: return vote
    return nsig is None or nsig < 0


def _root(s, b_flat):
    """Начало обозначения → (ступень ABC, остаток). None — это не аккорд.

    От набора зависит одно только голое «B» (`b_flat`). Слоговая ступень и «H»
    однозначны: в английской записи их не бывает вовсе, и принимать их можно
    не спрашивая, каким набором размечен лист.
    """
    m = ROOT.match(s)
    if not m: return None
    letter, syl = m.group(1), m.group(2) or ""
    rest = s[m.end():]
    # «Asus4» начинается на «As», но это A с sus4, а не ля-бемоль: слоговый «s»
    # уступает суффиксу
    if syl == "s" and rest.startswith("us"):
        syl, rest = "", s[1:]
    if rest[:1] in ("b", "#"):
        # альтерация набрана знаком, а не слогом. Знак уходит в ступень, а не в
        # остаток: иначе «Bbm» разбиралось бы как B с суффиксом «bm», которого
        # нет, и обозначение отвергалось целиком
        base = "B" if letter == "H" else letter
        return base + rest[0], rest[1:]
    if syl:
        return (GERMAN.get(letter + syl) or None), rest
    if letter == "B":
        return ("Bb" if b_flat else "B"), rest
    return GERMAN.get(letter, letter), rest


def normalize(raw, b_flat):
    """Обозначение из PDF → запись ABC. Пустая строка, если это не аккорд.

    Басовая нота разбирается тем же правилом, что и основная: «As/Es» — это
    Ab/Eb, и без разбора обеих половин обозначение отвергалось целиком.
    """
    s = unglyph(raw)
    if not s: return ""
    parts = s.split("/")
    if len(parts) > 2: return ""
    head = _root(parts[0], b_flat)
    if head is None or not SUFFIX.match(head[1]): return ""
    out = head[0] + head[1]
    if len(parts) == 2:
        bass = _root(parts[1], b_flat)
        # у басовой ноты суффиксов не бывает: «/Fis» — ступень и только
        if bass is None or bass[1]: return ""
        out += "/" + bass[0]
    # глиф, которому не нашлось имени, значит «мы не поняли обозначение», а не
    # «обозначение такое». Лучше отказ, который видно в замере, чем мусор в нотах
    return "" if set(out) - ALLOWED else out


def spans(doc):
    """Обозначения гармонии страницы: (страница, x, y, текст).

    Спан режется по пробелам, и координата берётся у первого символа части, а не
    у спана: PDF местами кладёт в один спан всю строку гармонии («Hm D/A Gmaj7»),
    и целиком она не аккорд, а привязать её к одной ноте значило бы потерять
    остальные.
    """
    out = []
    for pno, page in enumerate(doc):
        for b in page.get_text("rawdict")["blocks"]:
            for l in b.get("lines", []):
                for s in l["spans"]:
                    if "Chords" not in s["font"]: continue
                    part = []
                    for c in list(s["chars"]) + [{"c": " ", "bbox": s["bbox"]}]:
                        if c["c"].strip(): part.append(c); continue
                        if part:
                            out.append((pno, part[0]["bbox"][0], part[0]["bbox"][1],
                                        "".join(p["c"] for p in part)))
                            part = []
    return out


# хвост разорванного обозначения: альтерация, минор, цифра, скобка, бас или
# остаток лигатуры «maj». С буквы ступени хвост начаться не может
TAIL = re.compile(r"^[¨©‹“„Š\d()/]")


def merge(items):
    """Соседние спаны одного обозначения — в одно.

    Басовая нота с диезом («H7/D♯») приходит двумя спанами: у знака альтерации
    свой шрифтовый размер, и PDF разрывает строку на нём.

    Склейка идёт **по содержимому, а не по зазору**. Зазор её не различает: у
    Эппа соседние самостоятельные обозначения стоят в 3–14 пунктах друг от
    друга — ровно там же, где оказывается разрыв внутри одного. Прежний порог в
    30 пунктов слипал «Es» и «Es/Des» в несуществующий аккорд и съедал каждое
    четвёртое обозначение каталога.

    Порядок обхода — по строкам, а не по чистому `x`: обозначения приходят от
    всей страницы, и при сортировке по `x` между половинками одного вклинивался
    аккорд соседней системы с похожей координатой.
    """
    out = []
    for pno, x, y, t in sorted(items, key=lambda i: (i[0], round(i[2] / 4), i[1])):
        if (out and out[-1][0] == pno and abs(out[-1][2] - y) < 3
                and x - out[-1][3] < 30 and TAIL.match(t)):
            out[-1][4] += t
        else:
            out.append([pno, x, y, x + 6 * len(t), t])
    return [(p, x, y, t) for p, x, y, _, t in out]


def apply(doc, syss, sc, voice="S", b_flat=None):
    """Расставляет `chord` по событиям верхнего голоса. Возвращает число знаков.

    `b_flat` задаётся, когда про голое «B» известно снаружи: прогон идёт по
    каталогу целиком, и там повадка гравёра видна на соседних листах. Не задан —
    решает сам лист (`b_is_flat`).
    """
    items = merge(spans(doc))
    if not items: return 0
    if b_flat is None:
        # ключ берётся у первой системы: он и открывает лист, а смены посреди
        # песни ставятся своим знаком у той системы, где случились
        nsig = meta.key_signature(syss[0]) if syss else None
        b_flat = b_is_flat([t for _, _, _, t in items], nsig)
    n = 0
    for it, sy in zip(sc["systems"], syss):
        staff = (sy.get("vocal") or [None])[0] or sy.get("treble")
        if staff is None: continue
        sp = staff["space"]
        for pno, x, y, raw in items:
            if pno != sy["page"]: continue
            # обозначение стоит над своим станом, не дальше семи межлинейных:
            # выше начинается подпись предыдущей системы
            if not (staff["top"] - 7 * sp < y < staff["top"]): continue
            name = normalize(raw, b_flat)
            if not name: continue
            evs = [e for e in it["voices"][voice]["events"] if e["x"] > x - 2 * sp]
            if not evs: continue
            e = min(evs, key=lambda e: abs(e["x"] - x))
            if e.get("chord"): continue
            e["chord"] = name
            n += 1
    return n
