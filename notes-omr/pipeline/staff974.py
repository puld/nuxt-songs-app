# -*- coding: utf-8 -*-
"""Геометрия партитур «мелодия + аккомпанемент»: 974 и ему подобные.

Конвейер собран под хоровую вёрстку: система из двух станов — это SATB, по два
голоса на стан, различаемых направлением штиля. 974 набран иначе: сверху
одноголосная мелодия, снизу гитарная партия с буквенными обозначениями
аккордов, подтекстовка — в зазоре между ними, как у хора. Форма та же, смысл
другой, и разложенная по-хоровому система даёт вместо партии кашу: у мелодии
штили идут и вверх, и вниз по высоте ноты, поэтому деление по штилям режет
одну строку на два голоса, ни один из которых не набирает размер такта.

Два расхождения с общим случаем, и оба решаются здесь:

* **Вольта — не стан.** Скобка репризы нарисована горизонтальной линией длиннее
  двухсот пунктов, и `omr.staves_of` заводит на неё «стан» из одной линии с
  нулевым межлинейным. Дальше он становится отдельной системой, в неё попадают
  чужие глифы, а `satb.build` считает её такты — нумерация всей песни едет.
* **Нижний стан — аккомпанемент, а не второй хоровой.** Отличает его ключ: в
  хоровой паре снизу всегда басовый, а гитару пишут в скрипичном. Признак
  проверен по всему набору — тринадцать файлов дают `GF` и только 974 `GG`.

Аккомпанемент в ABC не переносится (см. `satb.build`), но такты его считаются:
без них сбилась бы нумерация. Поэтому гитарная строка объявляется
фортепианной — тем самым механизмом, которым уже разобрано вступление 119.

Подмена диспетчерская: файл, где нижний стан басовый, идёт прежним путём.
"""
import omr

_orig = {}

MIN_LINES = 5          # стан — это пять линий; всё, что короче, нарисовано не станом


def staves_of(page):
    """`omr.staves_of` без вырожденных «станов».

    Фильтр по числу линий, а не по длине или толщине: длина у скобки репризы
    станная (она тянется над несколькими тактами), а число линий подделать
    нечем — настоящий стан всегда пятилинейный.
    """
    return [s for s in _orig["staves_of"](page) if len(s["lines"]) >= MIN_LINES]


def is_accompaniment(sy):
    """Нижний стан двухстановой системы — аккомпанемент, а не второй хоровой?

    Решает ключ. Другие приметы обманывают: буквенные обозначения аккордов есть
    и над хоровой партитурой, число голосов на стане у гитары и у пары «тенор —
    бас» одинаково, а подтекстовка стоит в зазоре и там, и там.
    """
    import satb
    voc = sy.get("vocal") or []
    return len(voc) == 2 and satb.clef_of(sy, voc[-1]) != "F"


def has_lyrics_below(page, staff, below):
    """Есть ли слова под одиночным станом.

    Тем же признаком, что и `omr.has_lyrics`, но со строчной буквой: заглавные
    кириллические А, В, Е, К, М, Н, О, Р, С, Т, Х неотличимы от латинских, и
    аккорд «H7sus4» над вступлением 974 читался как слово песни. Слог
    подтекстовки без строчных букв не бывает.
    """
    lo = staff["bottom"]
    hi = below["top"] if below else lo + 12 * staff["space"]
    for w in page.get_text("words"):
        y = (w[1] + w[3]) / 2
        if lo < y < hi and any("а" <= c <= "я" or c == "ё" for c in w[4]):
            return True
    return False


def relayout(sy, page, below):
    """Переразложить систему, если она не хоровая. Возвращает, менялось ли что-то."""
    voc = sy.get("vocal") or []
    if is_accompaniment(sy):
        vocal, piano = voc[:1], voc[1:] + list(sy.get("piano") or [])
    elif len(voc) == 1 and not has_lyrics_below(page, voc[0], below):
        # одиночный стан без слов — инструментальное вступление или отыгрыш;
        # одиночная **вокальная** строка (1473) от него отличается подтекстовкой
        vocal, piano = [], voc + list(sy.get("piano") or [])
    else:
        return False
    sy["vocal"], sy["piano"] = vocal, piano
    # `treble`/`bass` — края той группы, по которой режутся такты: у системы без
    # вокала это аккомпанемент, иначе её такты выпали бы из нумерации песни
    ref = vocal or piano
    sy["treble"], sy["bass"] = ref[0], ref[-1]
    sy["ytop"], sy["ybot"] = ref[0]["top"], ref[-1]["bottom"]
    sy["band"] = omr.band_of(vocal, piano, below)
    return True


def analyse(path):
    doc, syss = _orig["analyse"](path)
    for i, sy in enumerate(syss):
        nxt = next((s for s in syss[i + 1:] if s["page"] == sy["page"]), None)
        below = nxt["staves"][0] if nxt and nxt.get("staves") else None
        relayout(sy, doc[sy["page"]], below)
    return doc, syss


def patch():
    """Подменить в `omr` две точки, где хоровая вёрстка считается единственной.

    Подмена, а не правка `omr`: разбор станов и раздача их по голосам — общий
    код, а исключение касается одного типа вёрстки, и держать его отдельным
    модулем дешевле, чем разводить в общем месте условиями.

    `staves_of` подменяется целиком (фильтр вырожденных станов безвреден для
    любого файла), а `analyse` дораскладывает уже готовые системы: решение
    «хор или аккомпанемент» требует ключа, то есть глифов, а их к моменту
    `split_staves` ещё не собрали.
    """
    if _orig: return
    _orig.update(staves_of=omr.staves_of, analyse=omr.analyse)
    omr.staves_of = staves_of
    omr.analyse = analyse
