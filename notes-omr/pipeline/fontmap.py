# -*- coding: utf-8 -*-
"""Опознание нотного шрифта и приведение его кодов к общему виду.

Издательские системы печатают ноты одним и тем же историческим набором кодов
(Maestro и совместимые), но в PDF он приезжает по-разному: в приватной области
(U+F0CF), голым байтом (U+00CF) или пропущенным через MacRoman (U+0153, «œ»).
Различать файлы по имени шрифта нельзя — оно у каждой типографии своё
(`Maestro`, `TT18o00`, `TTE2B42408t00`, `CIDFont+F1`), а в подмножествах имён
нет вовсе. Поэтому шрифт опознаётся по составу кодов: головка, флаги и ключи
встречаются в любой партитуре.
"""
import re

# семантика → коды нотной кодировки; у некоторых знаков кодов несколько,
# потому что часть издателей держит их в отдельном шрифте-компаньоне
SEM = {
    "head_f":   {0xCF},
    "head_h":   {0xFA},
    "head_w":   {0x77},
    "flag_up":  {0x6A}, "flag_dn":  {0x4A},
    "flag16_up": {0x72}, "flag16_dn": {0x52},
    "dot":      {0x2E, 0xAA},
    "clef_g":   {0x26}, "clef_f": {0x3F},
    "flat":     {0x62}, "sharp": {0x23}, "nat": {0x6E}, "dblsharp": {0xDC},
    # common time — «C» вместо цифр 4/4 (101 и ещё восемь файлов Эппа)
    "time_c":   {0x63},
    "rest_w":   {0xB7}, "rest_h": {0xEE}, "rest_q": {0xCE},
    "rest_8":   {0xE4}, "rest_16": {0xC5},
    "fermata_up": {0x55}, "fermata_dn": {0x75},
    # 0xB0 — верхняя половина акколады в шрифте Opus (1473). Без неё шрифт-компаньон
    # OpusSpecialStd не признавался нотным целиком (`music_fonts` требует, чтобы у
    # маленького шрифта все коды были знакомы), а вместе с акколадой из разбора
    # выпадала точка длительности 0xAA — она лежит в том же шрифте, и все ноты с
    # точкой читались короче на треть
    "brace":    {0x7B}, "bracket_top": {0xA1, 0xB0}, "bracket_bot": {0xA2},
    "segno":    {0x25}, "coda": {0xDE},
    # динамика: в Maestro она набрана нотным шрифтом, а не текстом, и «mp» —
    # один глиф (0x50), а не пара букв. Берём только те знаки, что встретились
    # в разобранных сборниках: угаданный код печатал бы в партитуре чужой
    # оттенок, а «не прочитано» просто оставляет ноту без него
    "dyn_p":    {0x70}, "dyn_f": {0x66}, "dyn_mp": {0x50}, "dyn_mf": {0x46},
    # скобки вокруг напоминающего знака альтерации — одним глифом, а не парой
    # скобок текста. В ABC не выводятся (напоминание адресовано певцу, а высоту
    # задаёт сам знак), но код записан: неопознанный код — сигнал, что в файле
    # встретилось что-то новое, и пустых сигналов там быть не должно
    "paren":    {0x61},
}
CODE = {c: name for name, cs in SEM.items() for c in cs}
DIGIT = {0x30 + i: str(i) for i in range(10)}      # цифры размера такта

# знаки, по которым шрифт признаётся нотным: они есть в любой партитуре
MARKERS = {0xCF, 0x6A, 0x4A, 0x26, 0x3F, 0xFA}

def cyr(t):
    """Кириллица, приехавшая мохибейком: cp1251, прочитанный как latin-1.

    В 658 ремарка «Припев» лежит в PDF как «Ïðèïåâ» — шрифт объявляет
    западную кодировку, а байты в нём русские, и слово не совпадало ни с одним
    правилом: в ABC от припева не осталось и пометки. Обратное преобразование
    однозначно — у настоящей латиницы («rit.», «Fine») старших байтов нет
    вовсе, и до перекодировки дело не доходит.
    """
    if not any("\u00c0" <= c <= "\u00ff" for c in t): return t
    try: s = t.encode("latin-1").decode("cp1251")
    except (UnicodeEncodeError, UnicodeDecodeError): return t
    return s if any("А" <= c <= "я" or c in "Ёё" for c in s) else t

# кириллица, распознанная по контурам, приезжает латиницей-двойником: у шрифта
# без ToUnicode буквы подбираются по начертанию, а курсивное «п» неотличимо от
# «n». В 664 так вышли «Hpuneв» вместо «Припев» и «Hepeвoд Д. A. Яcькo» вместо
# «Перевод Д. А. Ясько»
LOOKALIKE = str.maketrans("AaBEeKMHOoPpCcTXxyun", "АаВЕеКМНОоРрСсТХхуип")

def near(a, b):
    """Слова совпадают с точностью до одной замены, вставки или пропуска."""
    if a == b: return True
    if abs(len(a) - len(b)) > 1: return False
    if len(a) == len(b): return sum(x != y for x, y in zip(a, b)) == 1
    lo, hi = (a, b) if len(a) < len(b) else (b, a)
    return any(lo == hi[:i] + hi[i + 1:] for i in range(len(hi)))

# слова, которыми подписывают шапку: список закрытый, потому что запас «на одну
# букву» тем опаснее, чем короче слово, а фамилии и названия чинить нечем
HEAD_WORDS = ("перевод", "слова", "музыка", "напев", "обработка", "редакция",
              "гармонизация", "аранжировка", "мелодия", "текст")

def deglyph(t):
    """Латинские двойники → кириллица; известные слова шапки — по смыслу.

    Правило применяется послованно и только там, где кириллица уже есть:
    «Thompson» и «S.A.T.B.» набраны настоящей латиницей, и трогать их нельзя.
    Одной замены двойников мало для «Hepeвoд» — «Н» и «П» в курсиве похожи
    настолько, что выбор между ними угадывание, поэтому подписи шапки
    дотягиваются до словаря, если расходятся с ним на одну букву.
    """
    # инициал состоит из одной буквы, и своей кириллицы в нём нет: «Д. A. Яcькo»
    # так и оставался бы с латинской «A» посреди русского имени. Признак — вся
    # строка русская, а слово похоже на инициал
    ru = bool(re.search(r"[А-Яа-яЁё]", t))
    out = []
    for w in t.split(" "):
        if ru and re.match(r"^[A-Z]\.$", w):
            out.append(w.translate(LOOKALIKE)); continue
        if re.search(r"[А-Яа-яЁё]", w):
            w = w.translate(LOOKALIKE)
            core = w.strip(".,;:!?()").lower()
            for h in HEAD_WORDS:
                if core != h and near(core, h):
                    w = w.replace(w.strip(".,;:!?()"), h.capitalize()); break
        out.append(w)
    return " ".join(out)

def to_byte(ch):
    """Код символа → байт нотной кодировки, если это возможно."""
    c = ord(ch)
    if 0xF000 <= c <= 0xF0FF: return c - 0xF000
    if c < 0x100: return c
    for enc in ("mac-roman", "cp1252"):
        try: return ch.encode(enc)[0]
        except Exception: pass
    return None

def font_stats(doc):
    """Коды каждого шрифта документа с частотами."""
    out = {}
    for pg in doc:
        for b in pg.get_text("rawdict")["blocks"]:
            if b["type"]: continue
            for l in b.get("lines", []):
                for sp in l["spans"]:
                    d = out.setdefault(sp["font"], {})
                    for c in sp["chars"]:
                        k = to_byte(c["c"])
                        d[k] = d.get(k, 0) + 1
    return out

def music_fonts(doc):
    """Нотные шрифты документа: основной и его компаньоны.

    Основной опознаётся по опорным знакам. Компаньон (в нём держат точку
    длительности и части скобки) опорных знаков не содержит вовсе, поэтому
    берётся по признаку «маленький шрифт, все коды которого нотные».
    """
    st = font_stats(doc)
    main = {f for f, d in st.items()
            if len(MARKERS & set(d)) >= 3 and d.get(0xCF, 0) + d.get(0x153, 0) > 0}
    comp = set()
    for f, d in st.items():
        if f in main or len(d) > 6 or not d: continue
        codes = set(d) - {0x20, None}
        if codes and codes <= set(CODE) and not (codes & {0x2E}):
            comp.add(f)          # точку в тексте держит и Times: голая 0x2E не признак
    return main | comp, main

def unknown(doc):
    """Коды нотных шрифтов, которым не нашлось семантики, с частотами.

    Инвентарь, а не ошибка: пока список пуст, разбор видит в файле всё, что там
    напечатано нотным шрифтом. Непустой означает либо новый знак, либо чужую
    кодировку — и то и другое стоит посмотреть глазами, прежде чем доверять
    разбору. Исключение известно одно: в 752 строка темпа («♩. = 60_64») набрана
    тем же подмножеством шрифта, что и ноты, поэтому её буквы и цифры попадают
    сюда наравне со знаками.
    """
    st, out = font_stats(doc), {}
    music, _ = music_fonts(doc)
    for f in music:
        for c, n in st[f].items():
            if c is None or c == 0x20 or c in CODE or c in DIGIT: continue
            out[c] = out.get(c, 0) + n
    return out

def is_text_font(name, music):
    return name not in music
