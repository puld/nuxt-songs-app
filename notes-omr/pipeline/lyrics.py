# -*- coding: utf-8 -*-
"""Слова песни по системам: строки куплетов и привязка слогов к нотам.

Отличие от `score.lyrics` (он писался под 093): номера куплетов в сборнике
стоят **только у первой системы**, дальше строки идут без меток. Порядок строк
сверху вниз при этом сохраняется — на нём и держится наследование меток.
"""
import re
import fontmap

_WORDS = {}
_MUSIC = {}

def words_of(page):
    """Слова страницы, разрезанные там, где PDF потерял пробел.

    `get_text("words")` делит по символу пробела, а его в файле может не быть:
    в 655 «бе-рем сно-пы.» приезжает одним куском «бе-ремсно-пы.», и делить
    приходится по гласным — с дефисом переноса на границе слов, «бе- рем- сно-».
    В координатах разрыв виден: между «м» и «с» без малого два пункта, ровно
    как вокруг дефиса переноса, тогда как внутри слова буквы стоят вплотную —
    десятые доли. Порог берётся от кегля, а не в пунктах: 752 набран мельче.

    Разрыв засчитывается только между буквами: зазор вокруг дефиса переноса
    почти такой же (0.12 кегля против 0.14), и порог посередине оторвал бы
    дефис от слога — деление на слоги съехало бы во всех файлах разом. По
    буквам же во всём наборе разрыв единственный, тот самый в 655.

    Кэш — по имени файла и номеру страницы: разбор `rawdict` идёт на каждую
    систему, а страница между ними не меняется. Ключом нельзя брать `id`
    документа: закрытый объект освобождает адрес, следующий открытый получает
    тот же — и сводка по набору выдавала одному файлу слова другого.
    """
    key = (page.parent.name, page.number)
    if key in _WORDS: return _WORDS[key]
    doc = page.parent
    if doc.name not in _MUSIC: _MUSIC[doc.name] = fontmap.music_fonts(doc)[0]
    music = _MUSIC[doc.name]
    groups, cur, prev = [], [], None
    for b in page.get_text("rawdict")["blocks"]:
        for l in b.get("lines", []):
            for sp in l["spans"]:
                # нотный шрифт словом быть не может. Отбрасывать его приходится
                # здесь, а не в `rows_of`: приватные коды там уже ловились, но
                # Maestro отдаёт знаки голым байтом, и головка 0xCF проходила
                # через `fontmap.cyr` как кириллическая «П». В 119 полоса
                # подтекстовки достаёт до фортепианного стана, и весь его
                # аккомпанемент приезжал в куплеты — «П~П~Вер- ность Тво- я»
                if sp["font"] in music: prev = None; continue
                for c in sp["chars"]:
                    x0, y0, x1, y1 = c["bbox"]
                    ch, h = c["c"], y1 - y0
                    gap = (prev and prev[0].isalnum() and ch.isalnum() and h > 0
                           and (x0 - prev[1]) / h > 0.13)
                    if ch.isspace() or gap:
                        if cur: groups.append(cur); cur = []
                    if not ch.isspace(): cur.append(c); prev = (ch, x1)
                if cur: groups.append(cur); cur = []
                prev = None
    _WORDS[key] = out = [
        (min(c["bbox"][0] for c in g), min(c["bbox"][1] for c in g),
         max(c["bbox"][2] for c in g), max(c["bbox"][3] for c in g),
         "".join(c["c"] for c in g)) for g in groups]
    return out

def rows_of(page, top, bot, left=None):
    """Строки слов в полосе между станами, сверху вниз, каждая — по x.

    Строки собираются по **низу** бокса, а не по верху: верх зависит от того,
    попалась ли в слог высокая буква, и внутри одной строки гуляет на пять с
    лишним пунктов — больше, чем зазор между куплетами. Так в 658 слог «мешь»
    (у=537.3) отделился от своей строки (у=533.1) и пропал из куплета, оставив
    «при * ты мзду». Низ держится базовой линии: выносные вниз («р», «у», «д»)
    дают около двух пунктов при межстрочном интервале в двенадцать.
    """
    ws = []
    for w in words_of(page):
        if not (top < (w[1] + w[3]) / 2 < bot): continue
        # подпись стана («А.», «Т.», «Б.») стоит слева от нотоносца, и с тех пор
        # как полоса поиска опустилась под нижний стан, она попадала в текст: в
        # 752 куплеты начинались с «А.~Как ро- ня- я…», а под ними вырастала
        # строка «Б.~Т. * * * …». Подтекстовка всегда под нотами, то есть правее
        # начала стана, — слово целиком левее него текстом быть не может
        if left is not None and w[2] < left - 1: continue
        t = fontmap.cyr(w[4].strip())
        if not t or t in ("Score",): continue
        # нотные глифы приезжают в words как приватные коды и рвут строки
        if any("" <= c <= "" for c in t): continue
        # дефис переноса — отдельное слово в потоке, и без него «хо-тел» слиплось бы
        # в два самостоятельных слога; длинное тире (продление слога) не нужно
        if t not in ("-", "‐", "–", "—") and not re.search(r"[А-Яа-яЁё\d]", t): continue
        # в 664 дефис переноса приезжает длинным тире: шрифт без ToUnicode, и
        # его контур опознан по ближайшему похожему. Тире как знак препинания
        # так не стоит — оно отделено пробелами, а не приклеено к букве в конце
        # слога. Короткое тире не трогаем: им кончаются строки-отсылки (752), и
        # по нему они и отличаются от подтекстовки
        if len(t) > 1 and t[-1] == "—" and t[-2].isalpha(): t = t[:-1] + "-"
        # низ — для группировки, центр — наружу: по центру дальше решается, к
        # какому из станов строка ближе, и подменять его низом незачем
        ws.append((w[3], (w[1] + w[3]) / 2, w[0], w[2], t))
    ws.sort()
    rows, cur = [], []
    for w in ws:
        if cur and w[0] - cur[0][0] > 5: rows.append(cur); cur = []
        cur.append(w)
    if cur: rows.append(cur)
    return [sorted([t[1:] for t in r], key=lambda t: t[1]) for r in rows]

def split_by_labels(rows):
    """Строка припева стоит правее куплетной и попадает в тот же кластер по y."""
    out = []
    for toks in rows:
        cuts = [i for i, t in enumerate(toks) if i > 0 and re.match(r"^\d+(?:-\d+)?\.", t[3])]
        prev = 0
        for c in cuts + [len(toks)]:
            if toks[prev:c]: out.append(toks[prev:c])
            prev = c
    return out

def is_cue(toks, seen=()):
    """Строка-отсылка «2.Как скло–» — подсказка, с чего начнётся следующий куплет.

    Печатается столбиком в свободном месте у конца репризы (752, 974) и к нотам
    под собой отношения не имеет: это первые слова куплета, который пойдёт со
    следующего прохода.

    Признаков два, и порознь они не работают. Оборванный конец обязателен —
    у настоящей подтекстовки там слог или знак препинания, — но одного его мало:
    тире издатель ставит и длинное («2.Как скло–» в 752), и обычным дефисом
    («2.По -» в 974), а дефисом кончается всякая строка, у которой слово
    переносится на следующую систему. Поэтому второе условие — номер куплета уже
    встречался выше: настоящий куплет начинается один раз. Без него в 752 под
    отсылку попадала бы концовка «4.не у— — —гас.», напечатанная там же.
    """
    m = re.match(r"^(\d+(?:-\d+)?)\.", toks[0][3])
    if not m or m.group(1) not in seen or toks[-1][3][-1:] not in "\u2013\u2014-":
        return False
    # отсылка — это два-три слога, не строка: в 093 куплеты пронумерованы в
    # каждой системе, и одного повторного номера с переносом на конце хватало,
    # чтобы под правило ушёл весь текст восьми куплетов
    return len(cue_syllables(toks)[1]) <= 3

def cue_syllables(toks):
    """Метка и слоги отсылки; концевое тире отбрасывается."""
    lab, syls = parse_row(toks)
    while syls and not re.search(r"[А-Яа-яЁё]", syls[-1][1]): syls.pop()
    if syls:
        # концевое тире отсылки — знак обрыва, а не пунктуация: слово
        # продолжается следующим слогом, значит слог остаётся «слитным»
        t = re.sub(r"[~\s]*[\u2013\u2014-]+$", "", syls[-1][1])
        if t != syls[-1][1]: syls[-1][1], syls[-1][2] = t, True
    return lab, syls

def norm_syl(s):
    return s[1].split("~")[0].strip(" ,.;:!?—–").lower()

def apply_cues(per_sys, cues):
    """Вернуть началу куплета слоги, вынесенные издателем в отсылку.

    В 752 второй куплет напечатан со второго слова — «2. ня-ет-ся ко-лос», — а
    «Как скло–» стоит отдельной строкой у конца репризы. Само по себе это верно
    и на бумаге читается, но в подтекстовке ABC на месте первых слогов
    оставались пропуски, и куплет начинался с середины слова.

    Слоги приписываются в начало первой же системы, где куплет звучит, и берут
    координаты у первых слогов соседнего куплета: отсылка по смыслу занимает те
    же ноты, что и его начало.

    Отсылка бывает и напоминанием, а не заменой: в 974 «2.По–» повторяет первый
    слог куплета, напечатанного целиком. Отличие — совпадение текста: если
    начало уже на месте, приписывать нечего.
    """
    for lab, syls in cues.items():
        if not syls: continue
        for verses in per_sys:
            if lab not in verses: break
            ref = next((k for k in sorted((k for k in verses if k != lab and k.isdigit()),
                                          key=int)), None)
            if ref is None: break
            n = len(syls)
            if [norm_syl(s) for s in verses[lab][:n]] == [norm_syl(s) for s in syls]: break
            xs = [s[0] for s in verses[ref][:n]]
            if len(xs) < n or (verses[lab] and xs[-1] >= verses[lab][0][0]): break
            verses[lab] = [[x, s[1], s[2]] for x, s in zip(xs, syls)] + verses[lab]
            break
    return per_sys

VOWELS = "аеёиоуыэюя"

def syllables(t):
    """Кусок с двумя гласными — это два слога, слипшихся при извлечении.

    Дефис между ними в PDF нарисован линией, а не набран текстом («ли-ку-ю» в
    119), либо слова напечатаны вплотную и пробела между ними не осталось
    («бе-рем сно-пы» в 655, «пожнешь, что» в 658). Опереться не на что, кроме
    строения слога: гласная в нём ровно одна.

    Граница между гласными: знак препинания решает сам за себя, иначе первой
    части достаётся одна согласная из двух и более («зной-ный», «рем-сно») и ни
    одной, если согласная всего одна («ку-ю»). Мягкий знак к следующему слогу не
    уходит — он читается с предыдущей согласной.
    """
    pos = [i for i, c in enumerate(t) if c.lower() in VOWELS]
    if len(pos) < 2: return [(t, False)]
    out, prev = [], 0
    for a, b in zip(pos, pos[1:]):
        stop = [i for i in range(a + 1, b) if not t[i].isalpha()]
        if stop:
            cut, word = stop[-1] + 1, True     # запятая — граница слов, дефис не нужен
        else:
            cut, word = a + 1 + (1 if b - a - 1 >= 2 else 0), False
            while cut < b and t[cut].lower() in "ьъй": cut += 1
        if cut <= prev: continue
        out.append((t[prev:cut], not word))
        prev = cut
    out.append((t[prev:], False))
    return out

def split_hyphen(toks):
    """Токен с дефисом внутри — это несколько слогов, слипшихся при извлечении.

    Издатель ставит дефис переноса в отдельной позиции, и обычно PDF отдаёт
    слоги разными словами. Но при плотной печати («бес-плод-ным» в 656) зазоров
    не остаётся, и весь кусок приезжает одним токеном: три слога садились на
    одну ноту, а освободившиеся затыкались звёздочками.

    Ширина делится по буквам — своих координат у частей нет, а шрифт здесь
    моноширинным не является лишь слегка.
    """
    out = []
    for y, x0, x1, t in toks:
        parts = t.split("-")
        # дефис возвращается всем частям, кроме последней: он и означает «слог
        # продолжается», а `parse_row` читает именно его
        pieces = [(p, k < len(parts) - 1) for k, p in enumerate(parts)]
        if not all(p for p, _ in pieces):
            out.append((y, x0, x1, t)); continue
        pieces = [q for p, joined in pieces
                  for q in (syllables(p)[:-1] + [(syllables(p)[-1][0], joined)])]
        if len(pieces) < 2:
            out.append((y, x0, x1, t)); continue
        # ширина делится по фактической раскладке, а не по длине исходного
        # токена: у слитно напечатанного слова дефис появляется при разрезе
        # («знойный» → «зной-ный»), и на один знак раскладка длиннее. Считая по
        # исходной длине, последний слог вылезал правее конца слова и накрывал
        # начало следующего — в 664 «ный» слипался с «пол-» и получалось
        # «в~зной- ный- пол- день», слово с дефисом посреди
        total = sum(len(p) + (1 if joined else 0) for p, joined in pieces)
        w = (x1 - x0) / max(total, 1)
        off = 0
        for p, joined in pieces:
            a = x0 + off * w
            off += len(p) + (1 if joined else 0)
            out.append((y, a, a + len(p) * w, p + ("-" if joined else "")))
    return out

def drop_inner_hyphens(toks):
    """Дефис, попавший внутрь бокса соседнего слова, — это внутренний перенос.

    В 119 «ли-ку-ю» набрано так, что «кую,» приезжает одним токеном, а дефис
    между «ку» и «ю» — отдельным, с координатами внутри этого токена. Делить
    такой кусок всё равно приходится по гласным, а дефис после разреза
    приклеивался к последнему слогу: «ку- ю,-» вместо «ку- ю,».
    """
    words = [t for t in toks if t[3] not in ("-", "\u2010")]
    return [t for t in toks
            if t[3] not in ("-", "\u2010")
            or not any(w[1] < (t[1] + t[2]) / 2 < w[2] for w in words)]

def parse_row(toks):
    """Метка куплета и слоги строки; дефис в конце слога = продолжение слова."""
    label = None
    m = re.match(r"^(\d+(?:-\d+)?)\.$", toks[0][3])
    if m:
        label, toks = m.group(1), toks[1:]
    else:
        m2 = re.match(r"^(\d+(?:-\d+)?)\.(.+)$", toks[0][3])
        if m2:
            label = m2.group(1)
            toks = [(toks[0][0], toks[0][1], toks[0][2], m2.group(2))] + toks[1:]
    syls = []
    prev_x1 = None
    for _, x0, x1, t in split_hyphen(drop_inner_hyphens(toks)):
        if t in ("-", "‐"):
            if syls: syls[-1][2] = True
            continue
        if t in ("–", "—"):
            # тире как знак препинания приезжает отдельным токеном («Бог –»),
            # своей ноты у него нет: раньше оно просто пропадало, а отдельным
            # слогом сдвинуло бы всю строку на ноту вперёд. `~` в ABC и значит
            # «под одной нотой»
            if syls: syls[-1][1] += "~" + t
            continue
        joined = t.endswith("-")
        # дефис переноса издатель опускает, когда слоги и без него стоят впритык
        # («к звез|дам» в 093): зазор между словами всегда шире пробела, поэтому
        # слипшиеся токены — это один разорванный по нотам слог, а не два слова
        if (prev_x1 is not None and syls and not syls[-1][2] and x0 - prev_x1 < 0.5
                and t[:1].islower() and syls[-1][1][-1:].isalpha()):
            syls[-1][2] = True
        prev_x1 = x1
        # слог печатается под нотой по центру, а не левым краем: широкое слово
        # («плод-») начинается левее своей ноты и по краю уходило к предыдущей.
        # Дефис переноса стоит в промежутке до следующего слога и в центр не входит
        w = (x1 - x0) * (len(t) - 1) / len(t) if joined and len(t) > 1 else x1 - x0
        syls.append([x0 + w / 2, t[:-1] if joined else t, joined])
    return label, syls

def split_by_gap(rows):
    """Строка припева стоит на одном уровне с хвостом куплета.

    Разрыва между ними нет — хвост «ти".» и начало припева «О, как сильно…»
    напечатаны вплотную. Зато остальные хвосты куплетов в такой системе
    короткие и кончаются кучно: правее этой границы куплет уже не поётся.
    """
    if len(rows) < 3: return rows
    ends = sorted(r[-1][2] for r in rows)
    edge = ends[len(ends) // 2]
    if ends[-1] - edge < 60: return rows
    out = []
    for toks in rows:
        cut = next((i for i, t in enumerate(toks) if t[1] > edge + 10), None)
        if cut and toks[-1][2] - edge > 60:
            out.append(toks[:cut]); out.append(toks[cut:])
        else:
            out.append(toks)
    return [r for r in out if r]

def split_verse_column(rows, verses):
    """Столбик, в котором тексты куплетов расходятся, — куплеты, а не припев.

    Общее начало издатель печатает один раз, а дальше даёт по строке на куплет,
    выровняв их по левому краю: в 013 это «1-3. Ска-жи мне весть бла-гу-ю,» и три
    продолжения столбиком. Тем же способом набирают конец репризы, где столбиком
    стоят первые слоги куплетов следующего прохода (053: «Ска- О, Со Чтоб То-»).

    Строки столбика стоят на разных высотах, но поются на одних нотах, и без
    разреза все они получали метку припева. Дальше `collect` складывает слоги
    одной метки и сортирует по x — тексты пяти куплетов перемешивались в одну
    строку `w:`: «ю,~ска- чтоб я~жи,~Спа- по- си- стиг~ду- тель,».

    Признак — не совпадение x0 само по себе: слоги разных куплетов и так стоят
    под одними нотами. Нужно, чтобы с этой позиции часть строк **начиналась**
    (слева у них пусто), а другие её пересекали.

    Разрез принимается, только если правых частей ровно столько, сколько
    куплетов: столбик — это по строке на куплет, любое другое число значит, что
    за него принято что-то другое.
    """
    none = [None] * len(rows)
    if len(rows) < 3 or len(verses) < 2: return rows, none
    lo = min(t[1] for r in rows for t in r)
    # «заметно правее» — от самой левой строки системы, а не от края стана:
    # подтекстовка начинается под первой нотой, а та отстоит от края на ключ,
    # размер и знаки, и у разных песен по-разному
    orphan = [r[0][1] for r in rows if r[0][1] - lo > 60]
    if len(orphan) < 2 or max(orphan) - min(orphan) > 12: return rows, none
    xc = min(orphan) - 8
    out, forced, right = [], [], []
    for toks in rows:
        cut = next((i for i, t in enumerate(toks) if t[1] >= xc), len(toks))
        if cut == 0: right.append(toks); continue
        out.append(toks[:cut]); forced.append(None)
        if cut < len(toks): right.append(toks[cut:])
    if len(right) != len(verses): return rows, none
    right.sort(key=lambda toks: toks[0][0])
    for toks, n in zip(right, verses):
        out.append(toks); forced.append(str(n))
    return out, forced

def overlaps(a, b):
    """Две строки покрывают одни и те же такты — значит поются разом.

    Так печатают припев, где у мужских голосов свои слова: строки стоят одна над
    другой во всю ширину системы. Продолжение куплета выглядит иначе — оно
    начинается там, где предыдущая строка кончилась, и почти не перекрывается.
    """
    lo, hi = max(a[2], b[2]), min(a[4], b[4])
    span = min(a[4] - a[2], b[4] - b[2])
    return span > 0 and hi - lo > span * 0.5

def long_rows(rows):
    """Строки, тянущиеся через всю систему, когда рядом стоят короткие хвосты.

    В системе, где кончаются куплеты и начинается припев, хвосты («мой.», «вет?»)
    стоят столбиком слева, а припев начинается чуть правее — но левее середины,
    и по одному лишь началу от хвоста не отличался: в 744 он вставал третьей
    строкой столбца и сдвигал метки двух последних куплетов.

    Признак — длина относительно соседей, а не сама по себе: там, где номера
    напечатаны только у первой системы (656), все строки сплошные, и «длинная —
    значит припев» перепутало бы куплеты между собой.
    """
    lens = sorted(p[4] - p[2] for p in rows)
    med = lens[len(lens) // 2]
    return {id(p) for p in rows if p[4] - p[2] > max(3 * med, 60)}

def assign(blank, last_verses, last_right, verses_all, mid, ranged=False, band=None):
    """Метки безметочным строкам системы.

    Куплеты печатаются друг под другом в одном порядке и метку получают один раз —
    у первой системы; дальше строка опознаётся местом в столбце. Припев метки не
    имеет вовсе: он один на все куплеты, поэтому получает диапазон.
    """
    chorus = "%d-%d" % (verses_all[0], verses_all[-1]) if len(verses_all) > 1 else \
             (str(verses_all[0]) if verses_all else "1")
    rows = sorted(blank, key=lambda p: (p[3], p[2]))
    # разметка «1-7» и «8» в сборнике означает, что у последнего куплета своя
    # концовка припева: строк тоже две, но обе — сопрано, и путать их с текстом
    # мужских голосов нельзя. Такие метки в PDF напечатаны, голосовые — никогда
    if len(rows) == 2 and not ranged and overlaps(rows[0], rows[1]):
        # верхняя строка принадлежит верхнему стану, нижняя — нижнему
        return [(chorus, rows[0][1], rows[0][2], rows[0][3], rows[0][4]),
                (chorus + "@T", rows[1][1], rows[1][2], rows[1][3], rows[1][4])]
    out, rest = [], []
    seen = {}
    wide = long_rows(rows) if len(rows) > 2 else set()
    for p in rows:
        # куплет всегда начинается от левого края системы; строка, начатая правее
        # середины или растянутая на всю систему поверх коротких хвостов, — припев
        # или концовка, и в столбец куплетов её ставить нельзя
        if p[2] > mid or id(p) in wide: out.append((chorus, p[1], p[2], p[3], p[4])); continue
        # две строки на одном уровне: левая — хвост куплета, правая — начало припева
        key = round(p[3] / 4)
        if key in seen: out.append((chorus, p[1], p[2], p[3], p[4]))
        else: seen[key] = p; rest.append(p)
    # единственная строка, прижатая к верхнему стану, — текст сопрано, даже если
    # в прошлой системе справа стояла строка мужских голосов: наследование по
    # счёту строк отдавало ей последнюю систему 662 целиком
    if len(rest) == 1 and band and last_right and "@" in last_right[-1]:
        top, bot = band
        if abs(rest[0][3] - top) < abs(rest[0][3] - bot):
            last_right = []
    if len(rest) == len(last_verses) and last_verses:
        out += [(last_verses[i], p[1], p[2], p[3], p[4]) for i, p in enumerate(rest)]
    elif len(rest) == len(last_right) and last_right:
        out += [(last_right[i], p[1], p[2], p[3], p[4]) for i, p in enumerate(rest)]
    elif len(rest) == 1:
        out += [(chorus, rest[0][1], rest[0][2], rest[0][3], rest[0][4])]
    elif 1 < len(rest) < len(verses_all):
        # строк меньше, чем куплетов: в припеве у мужских голосов свои слова.
        # Метка «@T» означает тот же припев, но текст нижнего стана
        out += [((chorus if i == 0 else chorus + "@T"), p[1], p[2], p[3], p[4])
                for i, p in enumerate(rest)]
    else:
        out += [(last_verses[i] if i < len(last_verses) else chorus, p[1], p[2], p[3], p[4])
                for i, p in enumerate(rest)]
    return out

def scan_bot(sy, rest, bot):
    """Нижняя граница поиска слов: у SATB-системы — под нижним станом.

    Мужской хор поёт свой текст, и печатают его **под** нижним станом, а не в
    полосе между станами: в 658 так пропал весь припев тенора и баса — «Сей
    доб-ро-е се-мя во и-мя Хрис-та…». Полоса между станами до него не достаёт.

    Опускать границу можно только там, где нижний стан правда басовый: у вокала
    с фортепиано (1473, 1487, 974) полоса между станами и есть зона под голосом,
    а ниже лежит уже аккомпанемент. Признак — полоса кончается верхом нижнего
    стана. Снизу граница упирается в следующую систему: её собственная
    подтекстовка стоит ниже, но проверять это по расстоянию нельзя — в 658 до
    соседней системы двадцать восемь пунктов, ровно как до своей же строки.
    """
    bass = sy.get("bass")
    if not bass or abs(bot - bass["top"]) > 1: return bot
    sp = bass.get("space", 8)
    low = bass["bottom"] + 5.5 * sp
    nxt = next((s["ytop"] for s in rest if s["page"] == sy["page"]), None)
    return min(low, nxt - 2) if nxt else low

def collect(doc, systems):
    """[{метка: [[x, слог, слитно]]}] по системам.

    Полосу поиска задаёт сама система (`band`): «между верхним и нижним станом»
    у одиночной вокальной строки вырождается в пустую, а у вокала с фортепиано
    захватывает партию аккомпанемента. Считает её `omr.band_of` при разборе
    геометрии, здесь она только читается.
    """
    out, last_verses, last_right, seen = [], [], [], []
    cues = {}
    per_rows = []
    for si, sy in enumerate(systems):
        top, bot = sy.get("band") or (sy["treble"]["bottom"], sy["bass"]["top"])
        per_rows.append(split_by_gap(split_by_labels(
            rows_of(doc[sy["page"]], top, scan_bot(sy, systems[si + 1:], bot),
                    min(st["x0"] for st in sy.get("staves") or
                        [sy[k] for k in ("treble", "bass") if sy.get(k)])))))
    # номера куплетов нужны до разбора строк: столбик опознаётся по их числу, а
    # метки в нём не напечатаны. Считаются они по всей песне, а не по строкам
    # выше: в 025 столбик стоит в первой же системе, а номера напечатаны только
    # во второй — до неё песня выглядела бы вовсе бескуплетной
    labs = []
    for rows in per_rows:
        for toks in rows:
            m = re.match(r"^(\d+(?:-\d+)?)\.", toks[0][3])
            if m and m.group(1) not in labs: labs.append(m.group(1))
    allv_pre = sorted({n for l in labs for n in expand(l)})
    for si, sy in enumerate(systems):
        top, bot = sy.get("band") or (sy["treble"]["bottom"], sy["bass"]["top"])
        rows, forced = split_verse_column(per_rows[si], allv_pre)
        parsed = []
        for ri, toks in enumerate(rows):
            if is_cue(toks, seen):
                lab, syls = cue_syllables(toks)
                if lab and syls: cues.setdefault(lab, syls)
                continue
            lab, syls = parse_row(toks)
            if lab is None: lab = forced[ri]
            # строка без единой кириллической буквы — не подтекстовка: в полосе
            # между вокалом и фортепиано у 1487 лежит цифра метронома «60», и
            # без этого отсева она становилась лишним куплетом
            if not any(re.search(r"[А-Яа-яЁё]", t[1]) for t in syls): continue
            if syls: parsed.append((lab, syls, min(s[0] for s in syls), toks[0][0],
                                    max(s[0] for s in syls)))
        # куплеты без напечатанных номеров (1487): строки стоят столбиком, и
        # порядок сверху вниз — это и есть порядок куплетов. Без меток `assign`
        # сваливал их в один куплет, и слоги четырёх текстов слипались на одной
        # ноте. Правило включается только пока в песне не встретилось ни одной
        # метки: там, где номера напечатаны, они и решают
        if not seen and parsed and all(not p[0] for p in parsed) and len(parsed) > 1:
            parsed = [(str(i + 1),) + tuple(p[1:])
                      for i, p in enumerate(sorted(parsed, key=lambda p: (p[3], p[2])))]
        for lab, _, _, _, _ in parsed:
            if lab and lab not in seen: seen.append(lab)
        allv = sorted({n for l in seen for n in expand(l)})
        labeled = [p for p in parsed if p[0]]
        blank = [p for p in parsed if not p[0]]
        mid = (sy["treble"]["x0"] + sy["treble"]["x1"]) / 2
        ranged = any("-" in l for l in seen)
        parsed = labeled + (assign(blank, last_verses, last_right, allv, mid, ranged, (top, bot))
                            if blank else [])
        verses = {}
        for label, syls, _, _, _ in parsed:
            verses.setdefault(label, []).extend(syls)
        for k in verses: verses[k].sort(key=lambda s: s[0])
        if parsed:
            byy = sorted(parsed, key=lambda p: (p[3], p[2]))
            # припев отличается от куплета не меткой, а тем, что стоит один на всех
            last_verses = [p[0] for p in byy if "-" not in p[0] and "@" not in p[0]] or last_verses
            # строка, начавшаяся правее середины, — припев или концовка:
            # именно она продолжится в следующей системе
            right = [p[0] for p in byy if p[2] > mid]
            if right: last_right = right
        out.append(verses)
    return apply_cues(out, cues)
def expand(label):
    label = label.split("@")[0]
    if "-" in label:
        a, b = label.split("-"); return list(range(int(a), int(b) + 1))
    return [int(label)]

def numbers(per_sys):
    """Номера куплетов песни: метка «1-7» означает общий припев."""
    ns = set()
    for v in per_sys:
        for k in v: ns.update(expand(k))
    return sorted(ns)

# безударные односложные слова: предлог и союз своей ноты не получают, их поют
# со следующим словом («к тро-ну», «в дом»). Признак нужен там, где расстояния
# спорят на равных: в 660 «в дом» и «дом От-» отличались по сумме смещений на
# треть пункта, и раскладка выбирала между ними наугад
CLITIC = set("в во к ко с со у о об обо от ото до за на из изо по при про над "
             "под перед без для и а но не ни же ль ли бы б уж что как то".split())

def merge_cost(syl):
    """Во что обходится посадить слог на ноту вместе со следующим."""
    return 4.0 if syl[1].lower().strip(",.!?;:–—") in CLITIC else 30.0

def align(syls, nx, free, group=3, skip=12.0):
    """Слоги → ноты: монотонная раскладка с наименьшим суммарным смещением.

    Порог «слог принадлежит ближайшей ноте» ломался на четвертных: текст набран
    плотнее нот, и первый слог такта уползал к предыдущей ноте, а дальше вся
    строка ехала. Глобальное выравнивание такой сдвиг не даёт: лишние ноты
    (распев) достаются тем местам, где текст реально расступается.

    На одной ноте бывает и несколько слогов — но только целых слов: «к тро-ну»,
    «в дом». Внутри слова так не поют, поэтому группа разрешена лишь там, где
    все слоги, кроме последнего, слово заканчивают. Без этого ограничения
    раскладка сливала «плод-ным» и роняла остаток строки на такт вперёд.

    `free[j]` — можно ли ноте дать слог: под лигой распева и после тая нельзя.
    """
    K, N = len(syls), len(nx)
    INF = float("inf")
    dp = [[INF] * (N + 1) for _ in range(K + 1)]
    bk = [[None] * (N + 1) for _ in range(K + 1)]
    for j in range(N + 1): dp[0][j] = 0.0
    # пропуск ноты в середине строки не бесплатен: иначе раскладка охотно роняла
    # дырку, лишь бы подвинуть остаток строки на пункт ближе к своим нотам — в 093
    # так появлялись «*» посреди сплошного текста. Ноте под лигой пропуск ничего
    # не стоит: она и не должна брать слог
    for j in range(1, N + 1):
        for i in range(1, K + 1):
            best, arg = dp[i][j - 1] + (skip if free[j - 1] else 0.0), 0
            if free[j - 1]:
                cost, pen = 0.0, 0.0
                for g in range(1, min(group, i) + 1):
                    a = i - g
                    cost += abs(syls[a][0] - nx[j - 1])
                    # слог, оборванный переносом, слово не кончает — значит и ноту
                    # с соседом не делит
                    if g > 1 and syls[a][2]: break
                    if g > 1: pen += merge_cost(syls[a])
                    v = dp[a][j - 1] + cost + pen
                    if v < best: best, arg = v, g
            dp[i][j], bk[i][j] = best, arg
    # хвост системы без слов штрафовать нечем: строка куплета кончается там, где
    # кончается её текст, а дальше идут ноты припева или проигрыш
    j = min(range(K, N + 1), key=lambda t: dp[K][t]) if K <= N else N
    out, i = {}, K
    while j > 0:
        g = bk[i][j] if i else 0
        if g: out[j - 1] = (i - g, i); i -= g
        j -= 1
    return out

def word_of(take):
    """Слоги одной ноты: слитно через «~», перенос — дефисом на конце."""
    word = ""
    for j, s in enumerate(take):
        word += s[1]
        if j < len(take) - 1: word += "" if s[2] else "~"
    return word + ("-" if take[-1][2] else "")

def held(events):
    """Ноты, которые слога не принимают: распев под лигой и продление таем.

    Слог печатается под первой нотой лиги, а поётся на всех до её конца. Если
    следующая нота примет следующий слог, разъедется не одно место, а вся строка
    до конца системы — так в 656 и 661 расходились целые куплеты. Тай — тот же
    случай, только высота у нот одна.

    Лига фразировки, накрывающая несколько слогов, в этих сборниках у вокальных
    голосов не встречается: распев обозначают ею же, а фразировку не выписывают.
    """
    out, inside, tied = [], False, False
    for e in events:
        h = tied or inside
        # конец лиги — последняя нота распева, слога у неё нет
        if e.get("slurend"): h, inside = True, False
        if e.get("slur"): inside = True
        tied = bool(e.get("tie"))
        out.append(h)
    return out

def line_for(syls, events, verse_label=None):
    """Слоги → строка `w:` по нотам голоса.

    Нота, оставшаяся без слога, помечается по причине: под лигой распева и
    после тая слог тянется с предыдущей ноты, и в ABC это `_` — abcjs рисует
    под такой нотой линию продления, ровно как чёрточка в печатном сборнике.
    Звёздочка значит другое — «слога нет вовсе» (проигрыш, вступление), и
    ставить её на распев означало бы потерять сведения, которые у нас есть.
    """
    hold = held(events)
    free = [not h for h in hold]
    # слогов больше, чем свободных нот, даже с учётом групп — значит лиг нашлось
    # лишку: часть изданий рисует их и там, где слог не тянется. Тогда честнее
    # раскладка по всем нотам, чем слипшиеся в один токен слова
    if len(syls) > 3 * sum(free):
        free = [True] * len(events)
        hold = [False] * len(events)
    m = align(syls, [e["x"] for e in events], free)
    return " ".join(word_of(syls[m[k][0]:m[k][1]]) if k in m else "_" if hold[k] else "*"
                    for k in range(len(events)))
