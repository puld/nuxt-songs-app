# -*- coding: utf-8 -*-
"""Номера тактов, напечатанные в PDF, — единственный эталон внутри самого файла.

Сумма длительностей такта проверяет арифметику внутри такта, но не отвечает на
вопрос «а столько ли тактов мы вообще насчитали»: пропущенная тактовая черта
даёт два такта, слитых в один, и обе половины по отдельности сходятся. Издатель
печатает номер такта слева над каждой системой — сверка с ним ловит именно этот
класс ошибок.

Нумеруют не все и не одно и то же: в 662 слева стоят номера **строк** (1, 2,
3…), а не тактов. Отличаются они тем, что совпадают с порядковым номером
системы, — считать их эталоном нельзя, иначе сверка ругалась бы на верный
разбор.
"""
import re

def printed(page, sy):
    """Число слева над станом системы: номер такта или строки."""
    top, x0 = sy["ytop"], sy["treble"]["x0"]
    cand = [w for w in page.get_text("words")
            if re.fullmatch(r"\d+", w[4]) and w[0] < x0 + 30 and top - 24 < w[3] < top + 4]
    return int(cand[0][4]) if cand else None

def collect(doc, syss, sc):
    """Пары «наш номер первого такта системы — напечатанный в PDF»."""
    out, n = [], 1
    for i, (it, sy) in enumerate(zip(sc["systems"], syss)):
        p = printed(doc[sy["page"]], sy)
        if p is not None: out.append((i, n, p))
        n += it["nbars"]
    return out

def check(doc, syss, sc):
    """(вид, сколько сверено, расхождения).

    Вид: `такты` — номера тактов, сверка состоялась; `строки` — нумерация строк,
    сверять не с чем; `нет` — номеров в PDF не напечатано.
    """
    pairs = collect(doc, syss, sc)
    if not pairs: return "нет", 0, []
    if all(p == i for i, _, p in pairs) or all(p == i + 1 for i, _, p in pairs):
        return "строки", len(pairs), []
    bad = ["sys%d: PDF %d, наш %d" % (i, p, n) for i, n, p in pairs if p != n]
    return "такты", len(pairs), bad
