import { describe, it, expect } from 'vitest'
import { checkChordPasses, checkStropheChordPasses } from './chord-passes.js'

// Пометка прохода в аккорде: `{2:Dm}` звучит только во втором проходе
// ближайшего охватывающего повтора. Функция принимает строки .txt целиком
// (включая заголовок «#N Название») — так её и вызывает линтер.

/** Файл песни из строк тела. */
const song = (...bodyLines) => ['#1 Тест', '', ...bodyLines]

/** Только текст сообщений — номера строк проверяются там, где они важны. */
const messages = (lines) => checkChordPasses(lines).map((e) => e.message)

describe('checkChordPasses: корректная разметка', () => {
    it('аккорд без пометки — и в повторе, и вне его', () => {
        expect(checkChordPasses(song(
            '1. {Am}Славьте Христа,',
            '/{Dm}славьте любовь Христа! /2р.'
        ))).toEqual([])
    })

    it('пометка одного прохода внутри повтора', () => {
        expect(checkChordPasses(song('1. /{Am}Славьте {2:Dm}Христа! /2р.'))).toEqual([])
    })

    it('перечисление проходов внутри повтора', () => {
        expect(checkChordPasses(song('1. /{1,3:F}Славьте Христа! /3р.'))).toEqual([])
    })

    it('инлайновый аккорд: пометка идёт до подчёркивания', () => {
        expect(checkChordPasses(song('1. /Славьте {2:_G}Христа! /2р.'))).toEqual([])
    })

    it('пометка относится к ближайшему повтору, а не к внешнему', () => {
        // Внутренний повтор поётся 3 раза — проход 3 законен только для него
        expect(checkChordPasses(song('Припев:', '//{3:F}Аллилуйя! /3р. /2р.'))).toEqual([])
    })

    it('повтор, открытый и закрытый на разных строках', () => {
        expect(checkChordPasses(song(
            'Припев:',
            '/{2:Dm}Вечная слава,',
            'слава Христу! /2р.'
        ))).toEqual([])
    })

    it('строфы проверяются независимо', () => {
        expect(checkChordPasses(song(
            '1. /{2:Dm}Первый куплет. /2р.',
            '',
            'Припев:',
            '/{3:F}Припев. /3р.'
        ))).toEqual([])
    })

    it('пустой файл и отсутствующий аргумент', () => {
        expect(checkChordPasses([])).toEqual([])
        expect(checkChordPasses(undefined)).toEqual([])
    })
})

describe('checkChordPasses: пометка вне повтора', () => {
    it('аккорд с пометкой в строфе без репризы', () => {
        const errors = checkChordPasses(song('1. {2:Dm}Славьте Христа!'))

        expect(errors).toHaveLength(1)
        expect(errors[0].line).toBe(3)
        expect(errors[0].message).toBe(
            'Пометка прохода вне повтора: "{2:Dm}" — номеру не к чему относиться; '
            + 'без "/…/Nр." аккорд пишется "{Dm}"'
        )
    })

    it('аккорд стоит до открывающего слеша', () => {
        expect(messages(song('1. {2:Dm}Славьте /Христа! /2р.'))).toEqual([
            'Пометка прохода вне повтора: "{2:Dm}" — номеру не к чему относиться; '
            + 'без "/…/Nр." аккорд пишется "{Dm}"'
        ])
    })

    it('аккорд стоит после закрывающего маркера', () => {
        expect(messages(song('1. /Славьте /2р. {2:_G}Христа!'))).toEqual([
            'Пометка прохода вне повтора: "{2:_G}" — номеру не к чему относиться; '
            + 'без "/…/Nр." аккорд пишется "{_G}"'
        ])
    })
})

describe('checkChordPasses: номер больше счётчика', () => {
    it('третий проход у повтора на два раза', () => {
        const errors = checkChordPasses(song('1. /{3:F}Славьте Христа! /2р.'))

        expect(errors).toHaveLength(1)
        expect(errors[0].message).toBe(
            'Проход 3 в "{3:F}" — за пределами повтора "/2р.": номера идут от 1 до 2'
        )
    })

    it('в перечислении назван лишний номер', () => {
        expect(messages(song('1. /{1,4:F}Славьте Христа! /2р.'))).toEqual([
            'Проход 4 в "{1,4:F}" — за пределами повтора "/2р.": номера идут от 1 до 2'
        ])
    })

    it('лишних номеров несколько', () => {
        expect(messages(song('1. /{1,3,4:F}Славьте Христа! /2р.'))).toEqual([
            'Проходы 3, 4 в "{1,3,4:F}" — за пределами повтора "/2р.": номера идут от 1 до 2'
        ])
    })

    it('пометка внешнего повтора не сверяется со счётчиком внутреннего', () => {
        // «3:» относится к внутреннему повтору на 2 раза, хотя внешний поётся 4
        expect(messages(song('Припев:', '//{3:F}Аллилуйя! /2р. /4р.'))).toEqual([
            'Проход 3 в "{3:F}" — за пределами повтора "/2р.": номера идут от 1 до 2'
        ])
    })

    it('ошибка привязана к строке аккорда, а не закрывающего маркера', () => {
        const errors = checkChordPasses(song(
            'Припев:',
            '/{3:F}Вечная слава,',
            'слава Христу! /2р.'
        ))

        expect(errors).toHaveLength(1)
        expect(errors[0].line).toBe(4)
    })
})

describe('checkChordPasses: некорректный номер', () => {
    it('нулевой проход', () => {
        expect(messages(song('1. /{0:F}Славьте Христа! /2р.'))).toEqual([
            'Проход 0 в "{0:F}" — проходы нумеруются с единицы; '
            + 'аккорд в каждом проходе пишется "{F}"'
        ])
    })

    it('ноль в перечислении', () => {
        expect(messages(song('1. /{0,2:F}Славьте Христа! /2р.'))).toEqual([
            'Проход 0 в "{0,2:F}" — проходы нумеруются с единицы; '
            + 'аккорд в каждом проходе пишется "{F}"'
        ])
    })

    it('номер повторён в списке', () => {
        expect(messages(song('1. /{1,1:F}Славьте Христа! /3р.'))).toEqual([
            'Проход 1 в "{1,1:F}" повторён — каждый номер указывается один раз: "{1:F}"'
        ])
    })

    it('повтор номера в длинном списке', () => {
        expect(messages(song('1. /{1,2,1:F}Славьте Христа! /3р.'))).toEqual([
            'Проход 1 в "{1,2,1:F}" повторён — каждый номер указывается один раз: "{1,2:F}"'
        ])
    })
})

describe('checkChordPasses: пометка на всех проходах', () => {
    it('оба прохода двойного повтора', () => {
        expect(messages(song('1. /{1,2:F}Славьте Христа! /2р.'))).toEqual([
            '"{1,2:F}" помечает все проходы повтора "/2р." — это то же, что "{F}"'
        ])
    })

    it('единственный проход повтора на один раз', () => {
        expect(messages(song('1. /{1:F}Славьте Христа! /1р.'))).toEqual([
            '"{1:F}" помечает все проходы повтора "/1р." — это то же, что "{F}"'
        ])
    })

    it('порядок номеров значения не имеет', () => {
        expect(messages(song('1. /{3,1,2:_G}Славьте Христа! /3р.'))).toEqual([
            '"{3,1,2:_G}" помечает все проходы повтора "/3р." — это то же, что "{_G}"'
        ])
    })

    it('часть проходов — не ошибка', () => {
        expect(checkChordPasses(song('1. /{1,2:F}Славьте Христа! /3р.'))).toEqual([])
    })
})

describe('checkChordPasses: разбор маркеров', () => {
    it('слеш баса в аккорде не открывает повтор', () => {
        expect(checkStropheChordPasses([{ text: '{G/B}Бо{2:D7/F#}же!', line: 1 }])).toEqual([
            {
                line: 1,
                message: 'Пометка прохода вне повтора: "{2:D7/F#}" — номеру не к чему '
                    + 'относиться; без "/…/Nр." аккорд пишется "{D7/F#}"'
            }
        ])
    })

    it('слеш баса не мешает сверке со счётчиком', () => {
        expect(checkStropheChordPasses([
            { text: '/{G/B}Хва{2:A7/E}ла /2р.', line: 1 }
        ])).toEqual([])
    })

    it('слеш баса не подменяет счётчик повтора', () => {
        const errors = checkStropheChordPasses([{ text: '/{G/B}Хва{3:A7/E}ла /2р.', line: 1 }])

        expect(errors).toHaveLength(1)
        expect(errors[0].message).toContain('за пределами повтора "/2р."')
    })

    it('счётчик с пробелами и без точки', () => {
        expect(checkStropheChordPasses([{ text: '/{3:F}Хвала / 2 р', line: 1 }])).toHaveLength(1)
    })

    it('незакрытый повтор проверку не роняет — это забота баланса', () => {
        expect(checkChordPasses(song('1. /{2:Dm}Славьте Христа!'))).toEqual([])
    })

    it('закрытие без открытия проверку не роняет', () => {
        expect(checkChordPasses(song('1. {Am}Славьте Христа! /2р.'))).toEqual([])
    })

    it('скобка без пары не зацикливает разбор', () => {
        expect(checkChordPasses(song('1. /{Am}Славьте {Христа! /2р.'))).toEqual([])
    })

    it('текст без аккордов и мета-блок', () => {
        expect(checkChordPasses(song(
            '1. /Славьте Христа! /2р.',
            '@meta',
            'note: пометка {2:Dm} упомянута как текст',
            '@end'
        ))).toEqual([])
    })
})
