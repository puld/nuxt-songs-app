/**
 * Прокрутка при навигации.
 *
 * Дефолт Nuxt возвращает страницу наверх при каждой смене маршрута, и флаг
 * `scrollToTop: false` его не отменяет: он лишь убирает предустановленную
 * позицию, а в конце навигации `{ top: 0 }` возвращается всё равно. Из-за
 * этого страница, которая доводит список до нужного места сама («Все песни»
 * при переходе к разделу), получала вторую прокрутку поверх своей — с
 * заметным рывком.
 *
 * Здесь флаг значит буквально «не трогай прокрутку, страница разберётся».
 * Остальные маршруты ведут себя как раньше: назад — сохранённая позиция,
 * переход на другую страницу — наверх.
 */
export default {
    scrollBehavior(to, from, savedPosition) {
        if (to.meta.scrollToTop === false) return false
        if (savedPosition) return savedPosition
        // Смена query или якоря в пределах страницы — не повод прыгать наверх.
        if (to.path === from.path) return false

        return { left: 0, top: 0 }
    }
}
